// Read-only HTTP retrieval and complete compact-graph checks; no context execution.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { lstat, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'reference-bundle');
const outputIndex = process.argv.indexOf('--output');
assert(outputIndex >= 0 && process.argv[outputIndex + 1], '--output is required');
const output = path.resolve(process.argv[outputIndex + 1]);
assert(!output.startsWith(ROOT + path.sep), 'write the receipt outside the bundle');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const safe = relative => typeof relative === 'string' && relative.length <= 1024 &&
  !relative.includes('\\') && !relative.includes('\0') && !path.posix.isAbsolute(relative) &&
  relative.split('/').every(part => part && part !== '.' && part !== '..' && !part.startsWith('.'));
const files = new Map(); let total = 0;
async function load(relative) {
  assert(safe(relative), 'unsafe file in the checksum manifest');
  let current = ROOT;
  assert(!(await lstat(current)).isSymbolicLink(), 'bundle root must be regular');
  for (const part of relative.split('/')) {
    current = path.join(current, part);
    assert(!(await lstat(current)).isSymbolicLink(), 'bundle files must not use symlinks');
  }
  const info = await lstat(current);
  assert(info.isFile() && info.size <= 2 * 1024 * 1024, 'bundle file exceeds the client-check budget');
  const bytes = await readFile(current); total += bytes.length;
  assert(total <= 64 * 1024 * 1024, 'bundle exceeds the client-check budget');
  files.set(relative, bytes); return bytes;
}
const manifestBytes = await load('checksums.json');
const manifest = JSON.parse(manifestBytes);
assert(Object.keys(manifest.files).length <= 20_000, 'too many declared files');
for (const [relative, expected] of Object.entries(manifest.files)) {
  const bytes = await load(relative);
  assert.equal(bytes.length, expected.bytes, relative); assert.equal(sha(bytes), expected.sha256, relative);
}
const server = createServer((request, response) => {
  try {
    const relative = decodeURIComponent(new URL(request.url, 'http://localhost').pathname).slice(1);
    assert(safe(relative) && files.has(relative));
    response.writeHead(200, { 'Content-Type': 'application/octet-stream' });
    response.end(files.get(relative));
  } catch { response.writeHead(404); response.end('Not found'); }
});
const receipt = {schema:'okf-reference-client-access.v1', status:'failed',
  scope:'Exact generated bytes over loopback HTTP, full compact graph and source digests; remote publication and model answer quality are separate.',
  checker_sha256:sha(await readFile(fileURLToPath(import.meta.url)))};
try {
  await new Promise((resolve, reject) => {server.once('error', reject);server.listen(0, '127.0.0.1', resolve);});
  const base = `http://127.0.0.1:${server.address().port}/`;
  const retrieved = new Map();
  for (const [relative, expected] of files) {
    const response = await fetch(new URL(relative, base)); assert.equal(response.status, 200, relative);
    const bytes = Buffer.from(await response.arrayBuffer()); assert.equal(sha(bytes), sha(expected), relative);
    retrieved.set(relative, bytes);
  }
  const read = relative => JSON.parse(retrieved.get(relative));
  const descriptor = read('okf-bundle.json'), graph = read('okf-bundle.jsonld'), trail = read('walkthrough-data.json');
  const entities = new Map(graph['@graph'].map(entity => [entity['@id'], entity]));
  assert.equal(entities.size, graph['@graph'].length, 'duplicate semantic identities');
  const corpus = descriptor.corpora['ai-infrastructure-wiki']; let concepts=0, navigation=0;
  for (const node of Object.values(corpus.nodes)) {
    const entity=entities.get(node.semantic_id); assert(entity, node.id);
    assert.equal(entity.route,node.route); assert.equal(entity.core_role,node.core_role);
    if(node.core_role==='concept'){concepts++;assert.deepEqual(entity.frontmatter,node.frontmatter);}
    else if(node.core_role==='navigation')navigation++;
    else throw Error('unexpected core role');
  }
  const adjacency=new Map();
  for(const row of corpus.relationships){
    const assertion=entities.get(row.id);assert(assertion,row.id);
    assert.equal(assertion.source['@id'],row.source_iri);assert.equal(assertion.target['@id'],row.target_iri);assert.equal(assertion.predicate['@id'],row.predicate);
    const direct=entities.get(row.source_iri)[row.predicate];
    assert((Array.isArray(direct)?direct:[direct]).some(target=>target?.['@id']===row.target_iri));
    if(row.relationship_role==='concept')adjacency.set(row.source,[...(adjacency.get(row.source)||[]),row.target]);
  }
  assert.equal(sha(retrieved.get(trail.graph)),trail.graph_sha256);
  assert.equal(sha(retrieved.get(trail.descriptor)),trail.descriptor_sha256);
  for(const source of trail.source_documents)assert.equal(sha(retrieved.get(source.route)),source.sha256,source.route);
  for(const lane of trail.trails)for(const row of lane.assertions)assert(entities.has(row.id));
  for(const negative of trail.negative_controls){
    const pending=[negative.source], seen=new Set();
    while(pending.length){const route=pending.pop();if(seen.has(route))continue;seen.add(route);pending.push(...(adjacency.get(route)||[]));}
    assert(!seen.has(negative.target),'negative control has a directed concept path');
  }
  Object.assign(receipt,{status:'passed', files_retrieved:retrieved.size, manifest_sha256:sha(manifestBytes),
    concepts_verified:concepts,navigation_verified:navigation,assertions_and_direct_triples_verified:corpus.relationships.length,
    source_documents_verified:trail.source_documents.length,negative_controls:trail.negative_controls,
    bundle_id:descriptor.bundle_id,version:descriptor.version,snapshot:descriptor.snapshot,
    graph_sha256:sha(retrieved.get('okf-bundle.jsonld'))});
} catch(error){receipt.error=error.message;process.exitCode=1;}
finally{await new Promise(resolve=>server.close(resolve));await mkdir(path.dirname(output),{recursive:true});await writeFile(output,JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});}
console.log(JSON.stringify({status:receipt.status, files:receipt.files_retrieved,error:receipt.error}));
